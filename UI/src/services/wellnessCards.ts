/** 当天实际展示的卡片：同一天重复调用结果稳定，不使用随机数 */
export function pickDailyWellnessCard(date: Date): WellnessCard {
  // 用本机日期分量构造稳定天数，避免 toISOString 带来的时区跨日
  const dayIndex = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000
  )

  // 健身 / 饮食交替出现，避免连续几天都是同一类
  const category: WellnessCategory = dayIndex % 2 === 0 ? '健身' : '饮食'
  const pool = wellnessCards.filter(card => card.category === category)

  return pool[Math.floor(dayIndex / 2) % pool.length]
}
